// Store builds: sign release variants with the owner's upload key and ship without
// network access. Debug builds keep INTERNET so the dev client can reach Metro.
//
// Signing reads Gradle properties, typically from ~/.gradle/gradle.properties:
//   WUPIKO_UPLOAD_STORE_FILE, WUPIKO_UPLOAD_STORE_PASSWORD,
//   WUPIKO_UPLOAD_KEY_ALIAS, WUPIKO_UPLOAD_KEY_PASSWORD
// Without them, release APKs stay debug-signed for local QA, and bundleRelease fails
// so a debug-signed bundle can never be uploaded to Google Play.
const fs = require('fs');
const path = require('path');
const { withAppBuildGradle, withDangerousMod } = require('expo/config-plugins');

const MARKER = '// wupiko-upload-signing';

const signingConfig = `
        upload {
            ${MARKER}
            if (findProperty('WUPIKO_UPLOAD_STORE_FILE')) {
                storeFile file(findProperty('WUPIKO_UPLOAD_STORE_FILE'))
                storePassword findProperty('WUPIKO_UPLOAD_STORE_PASSWORD')
                keyAlias findProperty('WUPIKO_UPLOAD_KEY_ALIAS')
                keyPassword findProperty('WUPIKO_UPLOAD_KEY_PASSWORD')
            }
        }`;

const guard = `
${MARKER}
gradle.taskGraph.whenReady { graph ->
    def bundling = graph.allTasks.any { it.project == project && it.name == 'bundleRelease' }
    if (bundling && !findProperty('WUPIKO_UPLOAD_STORE_FILE')) {
        throw new GradleException('bundleRelease needs the Wupiko upload key. Set WUPIKO_UPLOAD_STORE_FILE and the related properties described in docs/release.md.')
    }
}
`;

const releaseManifest = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/android-release.js. Wupiko never uses the network. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">
    <uses-permission android:name="android.permission.INTERNET" tools:node="remove" />
</manifest>
`;

function withUploadSigning(config) {
  return withAppBuildGradle(config, (config) => {
    let source = config.modResults.contents;
    if (source.includes(MARKER)) return config;
    const debugSigning = /(    signingConfigs \{\n        debug \{[\s\S]*?\n        \})/;
    const releaseSigning = /(        release \{\n[\s\S]*?)signingConfig signingConfigs\.debug/;
    if (!debugSigning.test(source) || !releaseSigning.test(source)) {
      throw new Error('Update the Wupiko release-signing plugin for this Expo build.gradle template.');
    }
    source = source
      .replace(debugSigning, `$1${signingConfig}`)
      .replace(
        releaseSigning,
        "$1signingConfig findProperty('WUPIKO_UPLOAD_STORE_FILE') ? signingConfigs.upload : signingConfigs.debug"
      );
    config.modResults.contents = source + guard;
    return config;
  });
}

function withOfflineRelease(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const dir = path.join(config.modRequest.platformProjectRoot, 'app/src/release');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'AndroidManifest.xml'), releaseManifest);
      return config;
    },
  ]);
}

module.exports = function withWupikoRelease(config) {
  return withOfflineRelease(withUploadSigning(config));
};
