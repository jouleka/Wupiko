// Stopping a Wupiko alarm opens the app so the wake-up check-in is right there.
// iOS only finds App Intents declared in the app target, so the intent is generated
// here and registered with the alarm module when the app launches.
const fs = require('fs');
const path = require('path');
const { IOSConfig, withAppDelegate, withDangerousMod, withXcodeProject } = require('expo/config-plugins');

const FILE = 'WupikoIntents.swift';
const CALL = 'registerWupikoIntents()';
const source = `// Generated by plugins/ios-intents.js.
import AlarmKit
import AppIntents
import Foundation
internal import WupikoAlarm

/// Runs when the user stops a Wupiko alarm from the lock screen, the Dynamic
/// Island or the full-screen alert. It silences that alarm and brings Wupiko to
/// the front (after unlock) so the wake-up check-in is waiting.
struct OpenWupikoIntent: LiveActivityIntent {
  static let title: LocalizedStringResource = "Stop and open Wupiko"
  static let description = IntentDescription("Stops the alarm and opens Wupiko for the wake-up check-in.")
  static let openAppWhenRun = true
  static let isDiscoverable = false

  @Parameter(title: "Alarm ID")
  var alarmID: String

  init() {}

  init(alarmID: UUID) {
    self.alarmID = alarmID.uuidString
  }

  func perform() async throws -> some IntentResult {
    if let id = UUID(uuidString: alarmID) {
      try? AlarmManager.shared.stop(id: id)
    }
    return .result()
  }
}

func registerWupikoIntents() {
  WupikoAlarmIntents.stopAndOpen = { OpenWupikoIntent(alarmID: $0) }
}
`;

module.exports = function withWupikoIntents(config) {
  config = withDangerousMod(config, ['ios', async (config) => {
    const dir = path.join(config.modRequest.platformProjectRoot, config.modRequest.projectName);
    fs.writeFileSync(path.join(dir, FILE), source);
    return config;
  }]);
  config = withXcodeProject(config, (config) => {
    const name = config.modRequest.projectName;
    const filepath = `${name}/${FILE}`;
    if (!config.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: name, project: config.modResults });
    }
    return config;
  });
  return withAppDelegate(config, (config) => {
    let contents = config.modResults.contents;
    if (contents.includes(CALL)) return config;
    const launch = /(\n(\s*)return super\.application\(application, didFinishLaunchingWithOptions: launchOptions\))/;
    if (config.modResults.language !== 'swift' || !launch.test(contents)) {
      throw new Error('Update the Wupiko intents plugin for this Expo AppDelegate template.');
    }
    config.modResults.contents = contents.replace(launch, `\n$2${CALL}$1`);
    return config;
  });
};
